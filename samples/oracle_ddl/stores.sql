-- Bayou Retail ERP: store master (synthetic)
CREATE TABLE BAYOU_ERP.STORES (
    STORE_ID      NUMBER(6)          NOT NULL,
    STORE_NAME    VARCHAR2(80 CHAR)  NOT NULL,
    CITY          VARCHAR2(60 BYTE),
    STATE_CODE    CHAR(2),
    OPENED_ON     DATE,
    SQUARE_FEET   NUMBER(7),
    IS_ACTIVE     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_STORES PRIMARY KEY (STORE_ID)
)
TABLESPACE BAYOU_DATA
PCTFREE 10;
