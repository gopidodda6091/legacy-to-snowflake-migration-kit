-- Bayou Retail ERP: suppliers (synthetic)
CREATE TABLE BAYOU_ERP.SUPPLIERS (
    SUPPLIER_ID         NUMBER(8)       NOT NULL,
    SUPPLIER_NAME       VARCHAR2(120)   NOT NULL,
    COUNTRY_CODE        CHAR(2),
    PAYMENT_TERMS_DAYS  NUMBER(3),
    CREDIT_LIMIT        NUMBER(*,2),
    RATING              BINARY_DOUBLE,
    SUPPLIER_GUID       RAW(16),
    CONSTRAINT PK_SUPPLIERS PRIMARY KEY (SUPPLIER_ID)
);
