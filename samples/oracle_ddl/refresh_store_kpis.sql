CREATE OR REPLACE PROCEDURE BAYOU_ERP.REFRESH_STORE_KPIS AS
BEGIN
    DELETE FROM BAYOU_ERP.STORE_KPIS WHERE KPI_DATE = TRUNC(SYSDATE);
    INSERT INTO BAYOU_ERP.STORE_KPIS (KPI_DATE, STORE_ID, ON_HAND_VALUE)
    SELECT TRUNC(SYSDATE), i.STORE_ID, SUM(i.ON_HAND_QTY * p.UNIT_COST)
      FROM BAYOU_ERP.INVENTORY_SNAPSHOTS i
      JOIN BAYOU_ERP.PRODUCTS p ON p.PRODUCT_ID = i.PRODUCT_ID
     WHERE i.SNAPSHOT_DATE = TRUNC(SYSDATE)
     GROUP BY i.STORE_ID;
    COMMIT;
END;
