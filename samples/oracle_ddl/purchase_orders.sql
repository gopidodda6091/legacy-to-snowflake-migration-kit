-- Bayou Retail ERP: purchase orders (synthetic)
CREATE TABLE BAYOU_ERP.PURCHASE_ORDERS (
    PO_ID          NUMBER(12)     NOT NULL,
    SUPPLIER_ID    NUMBER(8)      NOT NULL,
    STORE_ID       NUMBER(6),
    ORDER_DATE     DATE           NOT NULL,
    EXPECTED_DATE  DATE,
    STATUS         VARCHAR2(12),
    TOTAL_AMOUNT   NUMBER(14,2),
    FX_RATE        NUMBER(9,6),
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_PURCHASE_ORDERS PRIMARY KEY (PO_ID)
)
TABLESPACE BAYOU_DATA;
