-- Bayou Retail ERP: loyalty customers (synthetic, no real people)
CREATE TABLE BAYOU_ERP.CUSTOMERS (
    CUSTOMER_ID     NUMBER(12)      NOT NULL,
    FIRST_NAME      NVARCHAR2(50),
    LAST_NAME       NVARCHAR2(50),
    EMAIL           VARCHAR2(120),
    LOYALTY_TIER    VARCHAR2(10),
    SIGNUP_DATE     DATE,
    LIFETIME_VALUE  NUMBER(14,2),
    LAST_SEEN_AT    TIMESTAMP(3) WITH TIME ZONE,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
);
